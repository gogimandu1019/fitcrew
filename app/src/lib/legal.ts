export const LEGAL_DOCS = { privacy: PRIVACY, terms: TERMS } as const;
export type LegalKey = keyof typeof LEGAL_DOCS;

export function toMarkdown(doc: LegalDoc): string {
  const parts = [`# ${doc.title}`, `시행일: ${doc.updated}`, doc.intro];
  for (const s of doc.sections) parts.push(`## ${s.heading}`, s.body.map((b) => `- ${b}`).join('\n'));
  return `${parts.join('\n\n')}\n`;
}
